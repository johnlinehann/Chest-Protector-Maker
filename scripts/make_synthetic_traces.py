"""Generate SYNTHETIC example traces (data/experimental/examples/) from known parameters.

They exist to demonstrate and test the calibration workflow — they are NOT measurements and are
marked `synthetic: true`, so fits from them can never be applied to the configuration.
Ground truth is written to examples/GROUND_TRUTH.yaml.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

import numpy as np
import yaml

from chestforge.core.calibration import require_calibrated
from chestforge.core.impact_sim import Rig, simulate_impact
from chestforge.core.padding import FoamLayer, load_material
from chestforge.core.projectile import load_projectile
from chestforge.units import LBF_TO_N, mph_to_ms
from chestforge.validation.fit import scaled_material
from chestforge.validation.traces import make_impactor, write_trace

OUT = Path(__file__).resolve().parent.parent / "data" / "experimental" / "examples"
FS_RAW = 50000.0
NTS_TRUTH = {"stiffness_scale": 1.08, "skin_damping_ratio": 0.30, "loading_surface_mass_kg": 0.11}
FOAM_TRUTH = {"A_Pa": 1.4, "E_Pa": 1.2, "B_Pa": 1.0, "rate_C": 0.7, "unloading_ratio": 0.5}


def _raw_record(r, rng, noise_lbf: float, pre_s: float = 0.0025):
    """Model's unfiltered load-cell force, resampled to 50 kHz, with pre-trigger and noise."""
    t = np.arange(0, r.t[-1] + pre_s, 1 / FS_RAW)
    f = np.interp(t - pre_s, r.t, r.force_raw_N, left=0.0, right=0.0)
    return t, f + rng.normal(0, noise_lbf * LBF_TO_N, len(t))


def main() -> None:
    rng = np.random.default_rng(2026)
    ball = load_projectile("baseball")
    nts = require_calibrated("baseball")
    true_nts = replace(nts, skin_stiffness_N_per_m=nts.skin_stiffness_N_per_m * NTS_TRUTH["stiffness_scale"],
                       skin_damping_ratio=NTS_TRUTH["skin_damping_ratio"],
                       loading_surface_mass_kg=NTS_TRUTH["loading_surface_mass_kg"])
    for mph in (29.1, 30.0, 30.9):
        r = simulate_impact(ball, true_nts, mph_to_ms(mph), None)
        t, f = _raw_record(r, rng, 0.8)
        write_trace(OUT / f"synthetic_bare_nts_{mph:.1f}mph.csv", t, f, {
            "rig": "nts", "projectile": "baseball", "velocity_mph": mph, "temperature_F": 72, "stack": "bare",
            "filtered": "false", "synthetic": "true",
            "source": "SYNTHETIC — generated by scripts/make_synthetic_traces.py (not a measurement)"})

    eva = load_material("eva_100")
    mystery = scaled_material(eva, np.array([FOAM_TRUTH[k] for k in ("A_Pa", "E_Pa", "B_Pa", "rate_C", "unloading_ratio")]))
    imp = make_impactor(2.5, 50.0)
    for v in (2.0, 3.0, 4.0):
        r = simulate_impact(imp, nts, v, (FoamLayer(mystery, 0.020),), rig=Rig.drop_tower())
        t, f = _raw_record(r, rng, 3.0)
        write_trace(OUT / f"synthetic_drop_eva_20mm_{v:.0f}ms.csv", t, f, {
            "rig": "drop_tower", "impactor_mass_kg": 2.5, "impactor_radius_mm": 50, "velocity_ms": v,
            "temperature_F": 72, "stack": "eva_100:20", "filtered": "false", "synthetic": "true",
            "source": "SYNTHETIC — 'EVA' sample with known parameter multipliers (not a measurement)"})

    (OUT / "GROUND_TRUTH.yaml").write_text(yaml.safe_dump(
        {"note": "Parameters used to generate the SYNTHETIC traces in this folder.",
         "nts": {"skin_stiffness_N_per_m": round(true_nts.skin_stiffness_N_per_m, 2),
                 "skin_damping_ratio": true_nts.skin_damping_ratio,
                 "loading_surface_mass_kg": true_nts.loading_surface_mass_kg},
         "eva_100_multipliers": FOAM_TRUTH}, sort_keys=False))
    print(f"wrote synthetic examples to {OUT}")


if __name__ == "__main__":
    main()
